-- Stable, unique payment references fit in the banking transfer memo.
ALTER TABLE training_contracts ADD COLUMN payment_reference BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE training_contracts ADD CONSTRAINT uq_contract_payment_reference UNIQUE(payment_reference);

-- A learner's receipt is a claim, never a confirmed financial transaction.
CREATE TABLE student_payment_submissions (
    id UUID PRIMARY KEY,
    contract_id UUID NOT NULL REFERENCES training_contracts(id),
    kind VARCHAR(20) NOT NULL CHECK(kind IN ('TUITION','DEPOSIT')),
    amount NUMERIC(18,2) NOT NULL CHECK(amount>0 AND amount=FLOOR(amount)),
    transfer_memo VARCHAR(120) NOT NULL,
    paid_on DATE NOT NULL,
    payer_name VARCHAR(160) NOT NULL,
    declared_bank_reference VARCHAR(120),
    note VARCHAR(1000),
    receipt_file_id UUID NOT NULL UNIQUE REFERENCES workflow_files(id),
    submitted_by BIGINT NOT NULL REFERENCES m_user(user_id),
    receiving_bank_code VARCHAR(20) NOT NULL,
    receiving_bank_bin VARCHAR(20) NOT NULL,
    receiving_bank_name VARCHAR(160) NOT NULL,
    receiving_account_number VARCHAR(40) NOT NULL,
    receiving_account_holder VARCHAR(160) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','MISMATCH','CONFIRMED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    reviewed_by BIGINT REFERENCES m_user(user_id),
    reviewed_at TIMESTAMP WITH TIME ZONE,
    review_note VARCHAR(1000),
    transaction_id UUID UNIQUE REFERENCES financial_transactions(id),
    statement_bank_reference VARCHAR(120),
    statement_amount NUMERIC(18,2),
    statement_memo VARCHAR(1000),
    statement_date DATE,
    CONSTRAINT ck_student_payment_confirmation CHECK(
        (status='CONFIRMED' AND transaction_id IS NOT NULL AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
        OR (status<>'CONFIRMED' AND transaction_id IS NULL)
    )
);
CREATE INDEX idx_student_payment_queue ON student_payment_submissions(status,created_at);
CREATE INDEX idx_student_payment_contract ON student_payment_submissions(contract_id,kind,status);

